const calculateReminderSchedule = (visitDateTime: Date, workingHoursStart: number = 9, workingHoursEnd: number = 18) => {
  const now = new Date();
  let firstReminder = new Date(now.getTime() + 2 * 60 * 60 * 1000);
  let secondReminder = new Date(now.getTime() + 4 * 60 * 60 * 1000);
  let autoCancel = new Date(now.getTime() + 5 * 60 * 60 * 1000);

  const adjustForWorkingHours = (date: Date) => {
    const hours = date.getHours();
    if (hours < workingHoursStart) {
      date.setHours(workingHoursStart, 0, 0, 0);
    } else if (hours >= workingHoursEnd) {
      date.setDate(date.getDate() + 1);
      date.setHours(workingHoursStart, 0, 0, 0);
    }
    return date;
  };

  return {
    firstReminderAt: adjustForWorkingHours(firstReminder).toISOString(),
    secondReminderAt: adjustForWorkingHours(secondReminder).toISOString(),
    autoCancelAt: adjustForWorkingHours(autoCancel).toISOString(),
    firstReminderSent: false,
    secondReminderSent: false,
  };
};

