export const getNotificationsByRoleFromMock = (userRole?: string) => {
  if (!userRole) return MOCK_APPROVAL_NOTIFICATIONS;
  
  return MOCK_APPROVAL_NOTIFICATIONS.filter(n => {
    if (!n.targetRoles || n.targetRoles.length === 0) return true;
    return n.targetRoles.includes(userRole as any);
  });
};

export const getUnreadNotificationCount = (userRole?: string) => {
  const filteredNotifications = getNotificationsByRoleFromMock(userRole);
  return filteredNotifications.filter(n => !n.read).length;
};
